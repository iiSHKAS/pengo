import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
const [version, imagePath, signaturePath, output, notesPath] = process.argv.slice(2);
if (!/^\d+\.\d+\.\d+$/.test(version ?? '') || !output || !notesPath) throw new Error('Usage: prepare-release.mjs VERSION APPIMAGE SIGNATURE OUTPUT NOTES');
const image = fs.readFileSync(imagePath);
if (!image.subarray(8,11).equals(Buffer.from([65,73,2]))) throw new Error('Not a type-2 AppImage');
const signature = fs.readFileSync(signaturePath,'utf8').trim();
const decoded = Buffer.from(signature,'base64').toString();
const trusted = decoded.split('\n').find(line=>line.startsWith('trusted comment: '));
if (!trusted || !trusted.split('\t').includes(`version:${version}`)) throw new Error('Signature is not bound to this release version');
const manifest = {version,notes:fs.readFileSync(notesPath,'utf8').trim(),pub_date:new Date().toISOString(),platforms:{'linux-x86_64':{signature,url:`https://github.com/iiSHKAS/pengo/releases/download/${version}/Pengo.AppImage`}}};
fs.mkdirSync(output,{recursive:true});
fs.writeFileSync(path.join(output,'Pengo.AppImage'),image,{mode:0o755});
fs.chmodSync(path.join(output,'Pengo.AppImage'),0o755);
fs.writeFileSync(path.join(output,'Pengo.AppImage.sig'),signature+'\n');
fs.writeFileSync(path.join(output,'latest.json'),JSON.stringify(manifest,null,2)+'\n');
const names=['Pengo.AppImage','Pengo.AppImage.sig','latest.json'];
fs.writeFileSync(path.join(output,'SHA256SUMS'),names.map(name=>crypto.createHash('sha256').update(fs.readFileSync(path.join(output,name))).digest('hex')+'  '+name+'\n').join(''));
console.log(`Prepared signed release ${version}: ${output}`);
